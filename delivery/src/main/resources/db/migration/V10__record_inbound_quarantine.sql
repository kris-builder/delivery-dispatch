CREATE TABLE inbound_quarantine (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    parcel_id BIGINT,
    receipt_id BIGINT,
    waybill_no VARCHAR(64) COLLATE utf8mb4_0900_bin,
    temporary_no VARCHAR(64),
    kind VARCHAR(24) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'UPSTREAM_REVIEW',
    note VARCHAR(500) NOT NULL,
    evidence_ref VARCHAR(255),
    reported_by BIGINT NOT NULL,
    reported_at DATETIME(6) NOT NULL,
    operation_receipt_id BIGINT NOT NULL,
    active_parcel_id BIGINT GENERATED ALWAYS AS (CASE WHEN status = 'UPSTREAM_REVIEW' THEN parcel_id ELSE NULL END) STORED,
    CONSTRAINT uq_inbound_quarantine_parcel UNIQUE (active_parcel_id),
    CONSTRAINT uq_inbound_quarantine_temporary UNIQUE (temporary_no),
    CONSTRAINT uq_inbound_quarantine_operation UNIQUE (operation_receipt_id),
    CONSTRAINT fk_inbound_quarantine_batch FOREIGN KEY (batch_id) REFERENCES inbound_batch (id),
    CONSTRAINT fk_inbound_quarantine_parcel FOREIGN KEY (parcel_id) REFERENCES parcel (id),
    CONSTRAINT fk_inbound_quarantine_receipt FOREIGN KEY (receipt_id) REFERENCES inbound_receipt (id),
    CONSTRAINT fk_inbound_quarantine_reporter FOREIGN KEY (reported_by) REFERENCES employee_account (id),
    CONSTRAINT fk_inbound_quarantine_operation FOREIGN KEY (operation_receipt_id) REFERENCES operation_receipt (id),
    KEY ix_inbound_quarantine_batch (batch_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
